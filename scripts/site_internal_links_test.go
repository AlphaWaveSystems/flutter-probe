package scripts

import (
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// Every internal link in the website's sources must point at a page that exists: a documentation page
// (src/content/docs/<path>.md, or <path>/index.md), a page of src/pages (<path>.astro, <path>/index.astro), or a file of public/.
// It reads the sources, not a build, so it needs no Node and runs with the other script tests. Anchors (#section) are not checked,
// only that the page exists; external links, mailto: and template expressions are skipped. The sidebar of astro.config.mjs is checked
// too: every `slug: '...'` and `link: '/...'` entry must name a page (the labels are not checked).

const siteRoot = "../website"

var (
	mdInternalLink   = regexp.MustCompile(`\]\((/[^)\s"]*)`)
	hrefInternalLink = regexp.MustCompile(`(?:href|src)="(/[^"\s]*)"`)
)

// sitePageExists says whether the site serves path (an absolute path such as /tools/ai/).
func sitePageExists(root, path string) bool {
	p := path
	if i := strings.IndexAny(p, "#?"); i >= 0 {
		p = p[:i]
	}
	if p == "" || p == "/" {
		return true
	}
	rel := strings.Trim(p, "/")
	// The pages of the sample dashboard (/demo/...) are generated by the build from demo-templates/ and are not committed: a checkout that has not built the
	// site has the templates only.
	if rel == "demo" || strings.HasPrefix(rel, "demo/") {
		sub := strings.TrimPrefix(strings.TrimPrefix(rel, "demo"), "/")
		if sub == "" {
			sub = "index.html"
		}
		if st, err := os.Stat(filepath.Join(root, "demo-templates", sub)); err == nil && !st.IsDir() {
			return true
		}
	}
	for _, c := range []string{
		filepath.Join(root, "src/content/docs", rel+".md"),
		filepath.Join(root, "src/content/docs", rel+".mdx"),
		filepath.Join(root, "src/content/docs", rel, "index.md"),
		filepath.Join(root, "src/content/docs", rel, "index.mdx"),
		filepath.Join(root, "src/pages", rel+".astro"),
		filepath.Join(root, "src/pages", rel, "index.astro"),
		filepath.Join(root, "src/pages", rel+".md"),
		filepath.Join(root, "public", rel),
		filepath.Join(root, "public", rel, "index.html"),
	} {
		if st, err := os.Stat(c); err == nil && !st.IsDir() {
			return true
		}
	}
	return false
}

// brokenInternalLinks returns the internal links in text that the site at root does not serve.
func brokenInternalLinks(root, text string) []string {
	var bad []string
	for _, re := range []*regexp.Regexp{mdInternalLink, hrefInternalLink} {
		for _, m := range re.FindAllStringSubmatch(text, -1) {
			link := m[1]
			if strings.HasPrefix(link, "//") || strings.ContainsAny(link, "{}$") || strings.HasPrefix(link, "/_astro") {
				continue
			}
			if !sitePageExists(root, link) {
				bad = append(bad, link)
			}
		}
	}
	return bad
}

var (
	sidebarSlug = regexp.MustCompile(`slug:\s*['"]([^'"]+)['"]`)
	sidebarLink = regexp.MustCompile(`link:\s*['"](/[^'"]*)['"]`)
)

// missingSidebarEntries returns the entries of an astro config's sidebar that name no page.
func missingSidebarEntries(root, config string) []string {
	var bad []string
	for _, m := range sidebarSlug.FindAllStringSubmatch(config, -1) {
		if !sitePageExists(root, "/"+strings.Trim(m[1], "/")+"/") {
			bad = append(bad, "slug "+m[1])
		}
	}
	for _, m := range sidebarLink.FindAllStringSubmatch(config, -1) {
		if !strings.ContainsAny(m[1], "{}$") && !sitePageExists(root, m[1]) {
			bad = append(bad, "link "+m[1])
		}
	}
	return bad
}

func TestSiteSidebarEntriesResolve(t *testing.T) {
	b, err := os.ReadFile(filepath.Join(siteRoot, "astro.config.mjs"))
	if err != nil {
		t.Fatal(err)
	}
	if n := len(sidebarSlug.FindAllString(string(b), -1)); n < 20 {
		t.Fatalf("found only %d sidebar slugs: the pattern does not match the config any more", n)
	}
	for _, bad := range missingSidebarEntries(siteRoot, string(b)) {
		t.Errorf("the sidebar names a page that does not exist: %s", bad)
	}
}

func TestMissingSidebarEntriesCases(t *testing.T) {
	root := t.TempDir()
	for _, f := range []string{"src/content/docs/tools/ai.md", "src/pages/pricing.astro"} {
		path := filepath.Join(root, f)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	cfg := "{ label: 'AI', slug: 'tools/ai' },\n{ label: 'Gone', slug: 'tools/ai-generation' },\n{ label: 'P', link: '/pricing/' },\n{ label: 'Q', link: '/nothing/' },\n{ label: 'X', link: 'https://example.com' }"
	got := strings.Join(missingSidebarEntries(root, cfg), "|")
	if got != "slug tools/ai-generation|link /nothing/" {
		t.Errorf("got %q", got)
	}
}

func TestSiteInternalLinksResolve(t *testing.T) {
	scanned := 0
	var problems []string
	err := filepath.WalkDir(filepath.Join(siteRoot, "src"), func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		switch filepath.Ext(p) {
		case ".md", ".mdx", ".astro":
		default:
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		scanned++
		for _, bad := range brokenInternalLinks(siteRoot, string(b)) {
			problems = append(problems, filepath.ToSlash(strings.TrimPrefix(p, siteRoot+string(filepath.Separator)))+": "+bad)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if scanned < 40 {
		t.Fatalf("scanned only %d files: the walk is not reaching the site sources", scanned)
	}
	sort.Strings(problems)
	for _, p := range problems {
		t.Errorf("an internal link has no page: %s", p)
	}
}

func TestBrokenInternalLinksCases(t *testing.T) {
	root := t.TempDir()
	for _, f := range []string{"src/content/docs/tools/ai.md", "src/content/docs/guide/index.md", "src/pages/pricing.astro", "public/llms.txt", "public/demo/index.html"} {
		path := filepath.Join(root, f)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	for _, tc := range []struct {
		name, text string
		want       []string
	}{
		{"a docs page", "[a](/tools/ai/)", nil},
		{"a docs page with an anchor", "[a](/tools/ai/#test-generation)", nil},
		{"a docs page without the slash", "[a](/tools/ai)", nil},
		{"an index page", "[a](/guide/)", nil},
		{"an astro page", `<a href="/pricing/">x</a>`, nil},
		{"a public file", "[a](/llms.txt)", nil},
		{"a public folder with an index", "[a](/demo/)", nil},
		{"the home page", "[a](/)", nil},
		{"a missing page", "[a](/tools/ai-generation/)", []string{"/tools/ai-generation/"}},
		{"a missing page in an href", `<a href="/tools/recorder/">x</a>`, []string{"/tools/recorder/"}},
		{"an external link", "[a](https://example.com/x)", nil},
		{"a protocol-relative link", "[a](//example.com/x)", nil},
		{"a template expression", `<a href={` + "`/x/${y}`" + `}>x</a> [a](/x/${y})`, nil},
		{"a link with a title", `[a](/advanced/hooks/ "title")`, []string{"/advanced/hooks/"}},
	} {
		got := brokenInternalLinks(root, tc.text)
		if strings.Join(got, "|") != strings.Join(tc.want, "|") {
			t.Errorf("%s: got %v, want %v", tc.name, got, tc.want)
		}
	}
}

// The sample dashboard pages are not committed: /demo/ and /demo/7-days.html resolve from the templates they are generated from, and a page without a template
// does not resolve.
func TestDemoPagesResolveFromTheirTemplates(t *testing.T) {
	root := t.TempDir()
	for _, f := range []string{"demo-templates/index.html", "demo-templates/7-days.html"} {
		path := filepath.Join(root, f)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte("x"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	// A folder under demo-templates is not a page, even if its name ends in .html.
	if err := os.MkdirAll(filepath.Join(root, "demo-templates", "folder.html"), 0o755); err != nil {
		t.Fatal(err)
	}
	for text, want := range map[string]string{
		"[a](/demo/)":             "",
		"[a](/demo)":              "",
		"[a](/demo/index.html)":   "",
		"[a](/demo/7-days.html)":  "",
		"[a](/demo/90-days.html)": "/demo/90-days.html",
		"[a](/demo/missing.html)": "/demo/missing.html",
		"[a](/demonstration/)":    "/demonstration/",
		"[a](/other/7-days.html)": "/other/7-days.html",
		"[a](/demo/folder.html)":  "/demo/folder.html",
	} {
		got := strings.Join(brokenInternalLinks(root, text), "|")
		if got != want {
			t.Errorf("%s: got %q, want %q", text, got, want)
		}
	}
}
