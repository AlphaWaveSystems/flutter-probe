// Generates src/probescript/dictionary.generated.ts from the ProbeScript docs, so that the editor's completions, hover
// text and snippets come from the same source as the documentation:
//   - the Command, Keyword and Hook tables of dictionary.md (command, syntax, description, category)
//   - the keyword and listed-word productions of grammar.md (the reserved words; the filler words are left out)
//
// Usage (from studio/frontend):
//   node scripts/gen-probescript-dictionary.mjs           write the generated module
//   node scripts/gen-probescript-dictionary.mjs --check   exit 1 when the committed module is out of date

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");

export const DICTIONARY_PATH = resolve(repoRoot, "website/src/content/docs/probescript/dictionary.md");
export const GRAMMAR_PATH = resolve(repoRoot, "website/src/content/docs/probescript/grammar.md");
export const OUTPUT_PATH = resolve(here, "../src/probescript/dictionary.generated.ts");

// The first column of the tables that list commands. Other tables (selectors, placeholders, the metrics and
// permission tables) have different columns and are not read.
const COMMAND_TABLE_FIRST_COLUMN = new Set(["Command", "Keyword", "Hook"]);

// splitRow splits one markdown table row into trimmed cells. A backslash-escaped pipe is a literal pipe.
function splitRow(line) {
  const inner = line.trim().replace(/^\|/, "").replace(/\|$/, "");
  return inner.split(/(?<!\\)\|/).map((cell) => cell.replace(/\\\|/g, "|").trim());
}

// plain removes the code markers from a cell, leaving the text a user would type.
function plain(cell) {
  return cell.replace(/`/g, "").trim();
}

function isCommandHeader(cells) {
  return (
    cells.length >= 3 &&
    COMMAND_TABLE_FIRST_COLUMN.has(plain(cells[0])) &&
    plain(cells[1]) === "Syntax" &&
    plain(cells[2]) === "Description"
  );
}

function isSeparator(cells) {
  return cells.every((cell) => /^:?-+:?$/.test(cell));
}

// parseDictionary reads every command table of dictionary.md. The "##" heading above a table is its category.
export function parseDictionary(markdown) {
  const commands = [];
  let category = "";
  let headerSeen = false;
  let inCommandTable = false;
  for (const raw of markdown.split("\n")) {
    const line = raw.trimEnd();
    const heading = /^##\s+(.+)$/.exec(line);
    if (heading) {
      category = heading[1].trim();
      headerSeen = false;
      inCommandTable = false;
      continue;
    }
    if (!line.startsWith("|")) {
      headerSeen = false;
      inCommandTable = false;
      continue;
    }
    const cells = splitRow(line);
    if (!headerSeen) {
      headerSeen = true;
      inCommandTable = isCommandHeader(cells);
      continue;
    }
    if (!inCommandTable || isSeparator(cells) || cells.length < 3 || !plain(cells[0])) {
      continue;
    }
    commands.push({
      command: plain(cells[0]),
      syntax: plain(cells[1]),
      description: cells[2],
      category,
    });
  }
  return commands;
}

// parseGrammar reads the reserved words from the ```ebnf blocks of grammar.md. The keyword and listed-word productions
// name them; the filler production names the words that carry no meaning of their own, and they are left out.
export function parseGrammar(markdown) {
  const keywords = [];
  const fillers = [];
  const blocks = [...markdown.matchAll(/```ebnf\n([\s\S]*?)```/g)].map((match) => match[1]);
  for (const block of blocks) {
    const text = block.replace(/\(\*[\s\S]*?\*\)/g, " "); // (* comments *) may quote words that are not productions
    for (const production of text.matchAll(/([a-z][a-z-]*)\s*=([^;]*);/g)) {
      const name = production[1];
      const target = name === "keyword" || name === "listed-word" ? keywords : name === "filler" ? fillers : null;
      if (!target) {
        continue;
      }
      for (const quoted of production[2].matchAll(/"([^"]+)"/g)) {
        if (/^[a-z][a-z-]*$/.test(quoted[1]) && !target.includes(quoted[1])) {
          target.push(quoted[1]);
        }
      }
    }
  }
  return keywords.filter((word) => !fillers.includes(word));
}

export function renderModule({ commands, keywords, sourceHash }) {
  return [
    "// Generated by studio/frontend/scripts/gen-probescript-dictionary.mjs from the ProbeScript docs.",
    "// Do not edit by hand. After a change under website/src/content/docs/probescript/, run",
    "// `npm run gen:probescript` in studio/frontend.",
    "",
    `export const SOURCE_SHA256 = ${JSON.stringify(sourceHash)};`,
    "",
    `export const COMMANDS = ${JSON.stringify(commands, null, 2)} as const;`,
    "",
    `export const KEYWORDS = ${JSON.stringify(keywords, null, 2)} as const;`,
    "",
  ].join("\n");
}

// generate returns the module text for the docs as they are now.
export function generate() {
  const dictionary = readFileSync(DICTIONARY_PATH, "utf8");
  const grammar = readFileSync(GRAMMAR_PATH, "utf8");
  const sourceHash = createHash("sha256").update(dictionary).update("\0").update(grammar).digest("hex");
  return renderModule({
    commands: parseDictionary(dictionary),
    keywords: parseGrammar(grammar),
    sourceHash,
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    const current = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, "utf8") : "";
    if (current !== text) {
      console.error("dictionary.generated.ts is out of date: run npm run gen:probescript in studio/frontend");
      process.exit(1);
    }
    console.log("dictionary.generated.ts is up to date");
  } else {
    writeFileSync(OUTPUT_PATH, text);
    console.log(`wrote ${OUTPUT_PATH}`);
  }
}
